"""Generate docs/mcp-tools.md from the MCP server's own tool schemas (names, descriptions, parameters,
annotations), so the reference cannot drift from the code.

    <mcp venv>/bin/python scripts/gen_tool_docs.py
"""
from __future__ import annotations

import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))

from odoo20_mcp import server as srv  # noqa: E402
from odoo20_mcp.tools import register_runtime  # noqa: E402

OUT = ROOT / "docs" / "mcp-tools.md"

GROUPS = [
    ("Workspace and lookup (read-only, static index)", [
        "odoo_status", "odoo_search", "odoo_grep", "odoo_module", "odoo_model", "odoo_method", "odoo_xmlid",
        "odoo_views", "odoo_access", "odoo_js", "odoo_assets"]),
    ("Quality", ["odoo_validate", "odoo_upgrade_code"]),
    ("Authoring", ["odoo_scaffold"]),
    ("Runtime (odoo-bin on allowlisted databases)", ["odoo_db", "odoo_test", "odoo_job", "odoo_server",
                                                       "odoo_shell"]),
    ("Live server (JSON-2)", ["odoo_live_call"]),
]

INTRO = """<!-- generated by scripts/gen_tool_docs.py from the server's tool schemas; do not edit by hand -->
# MCP tool reference

The `odoo20` MCP server exposes {count} tools. In Claude Code their full names are
`mcp__plugin_odoo20_odoo20__<tool>` (for example `mcp__plugin_odoo20_odoo20__odoo_model`); in other MCP
clients they keep the short names below.

- **Static tools** read the source index built from your Odoo 20 tree and extra addons paths. They never
  touch a database and are marked read-only, so Claude Code can run them in parallel.
- **`resolve="db"`** on `odoo_model`, `odoo_views` and `odoo_assets` asks Odoo itself (an `odoo-bin` helper
  on an allowlisted database) for the exact final result: fields, combined view arch, bundle file list.
- **Runtime tools** run `odoo-bin` with the `odoo_python` interpreter, only on databases matching the
  `db_allow` option. Tools that can change something carry `destructiveHint`, so Claude Code asks before
  running them (unless you allow them in your permission settings). See [safety.md](safety.md).
- Most tools take `format="markdown"` (default) or `format="json"`, plus `limit`/`offset` for pagination.
  Output is capped at about 25,000 characters with a hint on how to narrow the query.

| Tool | Kind | Purpose |
|---|---|---|
"""


def _type(schema: dict) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    for alt in schema.get("anyOf", []):
        if "enum" in alt:
            return " \\| ".join(f"`{v}`" for v in alt["enum"])
    if "anyOf" in schema:
        kinds = [a.get("type", "?") for a in schema["anyOf"] if a.get("type") != "null"]
        return " \\| ".join(kinds) + (" (optional)" if any(a.get("type") == "null" for a in schema["anyOf"]) else "")
    return schema.get("type", "?")


def _default(schema: dict, required: bool) -> str:
    if required:
        return "**required**"
    value = schema.get("default")
    if value is None:
        return "—"
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    return f"`{value!r}`" if isinstance(value, str) else f"`{value}`"


def _cell(text: str) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text.replace("<", "&lt;").replace(">", "&gt;")  # GitHub would render <chatter/> as a tag


async def collect() -> dict[str, dict]:
    register_runtime.register(srv.server)
    tools = await srv.server.list_tools()
    return {t.name: t.model_dump(by_alias=True, exclude_none=True) for t in tools}


def main() -> None:
    tools = asyncio.run(collect())
    grouped = [name for _, names in GROUPS for name in names]
    missing = sorted(set(tools) - set(grouped))
    if missing:
        sys.exit(f"tools not assigned to a group in gen_tool_docs.GROUPS: {missing}")
    lines = [INTRO.format(count=len(tools)).rstrip("\n")]
    for _, names in GROUPS:
        for name in names:
            ann = tools[name].get("annotations", {})
            kind = "read-only" if ann.get("readOnlyHint") else ("asks first" if ann.get("destructiveHint") else "writes files")
            first = _cell(tools[name].get("description", "").split("\n\n")[0]).split(". ")[0].rstrip(".")
            lines.append(f"| [`{name}`](#{name}) | {kind} | {first} |")
    lines.append("")
    for title, names in GROUPS:
        lines.append(f"## {title}\n")
        for name in names:
            tool = tools[name]
            schema = tool.get("inputSchema", {})
            required = set(schema.get("required", []))
            lines.append(f"### {name}\n")
            lines.append(_cell(tool.get("description", "")) + "\n")
            props = schema.get("properties", {})
            if props:
                lines.append("| Parameter | Type | Default | Description |")
                lines.append("|---|---|---|---|")
                for pname, pschema in props.items():
                    lines.append(f"| `{pname}` | {_type(pschema)} | {_default(pschema, pname in required)} | "
                                 f"{_cell(pschema.get('description', ''))} |")
                lines.append("")
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(tools)} tools)")


if __name__ == "__main__":
    main()
