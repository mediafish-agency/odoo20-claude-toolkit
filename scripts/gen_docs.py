"""Generate skill reference files from the validator catalogue and the source index (no hand edits).

    python scripts/gen_docs.py            # uses the plugin venv + installed index

Outputs:
  skills/develop/references/version-traps.md   <- mcp/odoo20_mcp/validate/rules.py
  skills/views/references/widget-index.md      <- registry.category("fields") entries in the index
  skills/owl/references/registry-index.md      <- every JS registry category in the index
  skills/owl/references/icons-mapping.md       <- odoo/upgrade_code/material_symbols_icons_mapping.py + shipped subset
"""
from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "mcp"))
# data dir / Odoo root: same resolution as the MCP server (ODOO20_DATA_DIR, ODOO20_ROOT, auto-detection)

from odoo20_mcp import context  # noqa: E402
from odoo20_mcp.validate.rules import RULES  # noqa: E402

HEADER = "<!-- generated by scripts/gen_docs.py; do not edit by hand -->\n"
AREA_TITLES = {
    "security": "Security (ir.access)", "orm": "ORM / Python", "mail": "Mail", "http": "HTTP / controllers",
    "tests": "Tests", "reports": "Reports", "views": "Views", "qweb": "QWeb", "icons": "Icons",
    "data": "Data files", "owl": "OWL / JavaScript", "frontend": "Public frontend", "pos": "Point of Sale",
    "scss": "SCSS", "manifest": "Manifest", "assets": "Assets",
}


def md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def version_traps() -> str:
    out = [HEADER, "# Odoo 19 -> 20 traps (validator catalogue)", "",
           "Every rule below is checked by `odoo_validate` and the PostToolUse hook. `Fixed by` names the Odoo "
           "`upgrade_code` script that rewrites it automatically (`odoo_upgrade_code`). Suppress a deliberate case "
           "with a comment containing `odoo20-ignore: RULE_ID` on that line.", ""]
    by_area: dict[str, list] = defaultdict(list)
    for rule in RULES:
        by_area[rule.area or "other"].append(rule)
    for area, rules in by_area.items():
        out += [f"## {AREA_TITLES.get(area, area.title())}", "",
                "| Rule | Sev. | Files | Trap | Odoo 20 way | Fixed by | Evidence |", "|---|---|---|---|---|---|---|"]
        for r in rules:
            out.append(f"| {r.id} | {r.severity} | {', '.join(sorted(r.kinds))} | {md_escape(r.title)} | "
                       f"{md_escape(r.fix)} | {r.fixed_by or ''} | `{r.source}` |")
        out.append("")
    out += ["## Cross-module checks (odoo_validate, index-backed)", "",
            "| Rule | Meaning |", "|---|---|",
            "| MAN100-MAN108 | manifest: unparsable, unknown depends, missing data file, ir.access not last, no license, "
            "foreign major version (installable=False), data file never loaded, asset glob matches nothing, no author |",
            "| PYI001 | python file/package never imported |",
            "| PYM001 / PYM002 | `_inherit` target or relational comodel not defined in the dependencies |",
            "| VIEW001-VIEW004 | view model unknown, field not on model, button calls a private or missing method |",
            "| SEC101-SEC106 | ir.access: invalid operation, model name/xmlid misuse, bad domain, c/u/d for portal/public/"
            "everyone, model without any permission row (default deny) |",
            "| REF001-REF003 | xmlid from a module that is not a dependency, unknown module, xmlid not found |",
            "| JSI001-JSI003 | JS import does not resolve, comes from a non-dependency, imports a name the module does not export |",
            "| RNG001 / RNG002 | data file rejected by odoo/import_xml.rng, primary view rejected by base/rng/<type>_view.rng |",
            ""]
    return "\n".join(out)


def widget_index(con) -> str:
    rows = con.execute("SELECT key, module, file, line, value FROM js_registry WHERE category='fields' ORDER BY key, module, file, line").fetchall()
    out = [HEADER, "# Field widget index (registry.category(\"fields\"))", "",
           f"{len(rows)} keys registered in the Odoo 20 tree. Keys prefixed with a view type (`list.`, `form.`, `card.`, "
           "`calendar.`, ...) override the generic widget in that view type. Use `odoo_js(registry=\"fields\", key=...)` "
           "for details and read the component before relying on its options.", "",
           "| widget | module | defined in |", "|---|---|---|"]
    for r in rows:
        out.append(f"| `{r['key']}` | {r['module']} | `{r['file']}:{r['line']}` |")
    return "\n".join(out) + "\n"


def registry_index(con) -> str:
    cats = con.execute("SELECT category, count(*) n, group_concat(DISTINCT module) mods FROM js_registry "
                       "GROUP BY category ORDER BY n DESC, category").fetchall()
    out = [HEADER, "# JS registry categories in Odoo 20", "",
           "`registry.category(name).add(key, value)` call sites found in `static/src` and `static/tests` of every "
           "addon (`services (plugins)` lists `services.add(PluginClass)` from `@web/core/services`). "
           "Query one category with `odoo_js(registry=\"<name>\")`.", "",
           "| category | entries | sample keys | modules (first 6) |", "|---|---|---|---|"]
    for c in cats:
        keys = [r[0] for r in con.execute("SELECT key FROM js_registry WHERE category=? ORDER BY key LIMIT 5", (c["category"],))]
        mods = sorted(set((c["mods"] or "").split(",")))  # group_concat order depends on indexing order
        out.append(f"| `{c['category']}` | {c['n']} | {', '.join(f'`{k}`' for k in keys)} | {', '.join(mods[:6])} |")
    return "\n".join(out) + "\n"


def icons_mapping(odoo_root: Path) -> str:
    src = odoo_root / "odoo" / "upgrade_code" / "material_symbols_icons_mapping.py"
    tree = ast.parse(src.read_text(encoding="utf-8"))
    mapping: dict = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == "FA_TO_MATERIAL":
            call = node.value
            arg = call.args[0] if isinstance(call, ast.Call) else call
            mapping = ast.literal_eval(arg)
    wishlist_path = odoo_root / "addons" / "web" / "tooling" / "icons" / "icons_wishlist.txt"
    shipped = {line.strip() for line in wishlist_path.read_text().splitlines() if line.strip() and not line.startswith("#")}
    out = [HEADER, "# Font Awesome -> Material Symbols (Odoo 20)", "",
           f"From `odoo/upgrade_code/material_symbols_icons_mapping.py` ({len(mapping)} entries). Use as "
           "`<i class=\"oi\" data-icon=\"NAME\"/>` (add `oi-filled` when the filled column says yes). "
           f"\"Shipped\" = present in the font subset (`addons/web/tooling/icons/icons_wishlist.txt`, {len(shipped)} "
           "icons; `oi_*` brand glyphs come from the separate `web.odoo_ui_icons` font): an icon outside both renders no glyph.", "",
           "| fa-… | Material name | filled | shipped |", "|---|---|---|---|"]
    for fa, value in sorted(mapping.items()):
        name, filled = (value if isinstance(value, (tuple, list)) else (value, False))[:2]
        status = "yes" if name in shipped else ("odoo_ui_icons" if name.startswith("oi_") else "**no**")
        out.append(f"| `fa-{fa}` | `{name}` | {'yes' if filled else ''} | {status} |")
    return "\n".join(out) + "\n"


def main() -> None:
    im = context.index()
    im.build()
    con = im.db()
    targets = {
        ROOT / "skills/develop/references/version-traps.md": version_traps(),
        ROOT / "skills/views/references/widget-index.md": widget_index(con),
        ROOT / "skills/owl/references/registry-index.md": registry_index(con),
        ROOT / "skills/owl/references/icons-mapping.md": icons_mapping(context.config().odoo_root),
    }
    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
