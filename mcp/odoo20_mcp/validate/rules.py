"""Catalogue of Odoo <= 19 habits that break or are deprecated in Odoo 20.

Single source of truth: the validator, the PostToolUse hook and the skills'
``version-traps.md`` (generated by scripts/gen_docs.py) all read this list.

Every rule cites ``source``: a path in the Odoo 20 tree that proves the change
(tests assert these paths exist). Patterns run on comment-stripped text.
"""
from __future__ import annotations

import re
from collections.abc import Callable
from dataclasses import dataclass, field

from lxml import etree

ERROR, WARNING, INFO = "error", "warning", "info"

# file kinds (see index/scanner.file_kind): py, xml (server), owl_xml (static/), js, scss, csv, manifest


@dataclass(frozen=True)
class Rule:
    id: str
    severity: str
    kinds: frozenset[str]
    title: str
    fix: str
    source: str
    pattern: str | None = None
    flags: int = 0
    check: Callable[[str, str], list[tuple[int, str]]] | None = None
    fixed_by: str | None = None
    area: str = ""
    hint: str | None = None  # raw-text prefilter for `check` rules
    compiled: re.Pattern | None = field(default=None, compare=False, repr=False)

    def regex(self) -> re.Pattern | None:
        if self.pattern is None:
            return None
        if self.compiled is None:
            object.__setattr__(self, "compiled", re.compile(self.pattern, self.flags))
        return self.compiled


def R(id, severity, kinds, title, fix, source, pattern=None, *, flags=0, check=None, fixed_by=None, area="", hint=None):
    kinds = frozenset(kinds.split()) if isinstance(kinds, str) else frozenset(kinds)
    return Rule(id, severity, kinds, title, fix, source, pattern, flags, check, fixed_by, area, hint)


