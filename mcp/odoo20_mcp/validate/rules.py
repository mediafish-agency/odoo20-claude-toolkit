def _tcall_with_tset(text: str, rel: str) -> list[tuple[int, str]]:
    """Server QWeb: <t t-call="x"><t t-set="a" .../></t> no longer passes `a` to the callee."""
    if "t-call" not in text or "t-set" not in text:
        return []
    try:
        root = etree.fromstring(text.encode(), etree.XMLParser(recover=True, huge_tree=True))
    except etree.XMLSyntaxError:
        return []
    if root is None:
        return []
    hits = []
    for el in root.iter():
        if isinstance(el.tag, str) and el.get("t-call"):
            for child in el:
                if isinstance(child.tag, str) and child.get("t-set"):
                    hits.append((child.sourceline or el.sourceline or 0, f"t-set=\"{child.get('t-set')}\" inside t-call=\"{el.get('t-call')}\""))
    return hits


def _owl_bundle_without_compat(text: str, rel: str) -> list[tuple[int, str]]:
    """A manifest bundle that ships lib/owl/owl.js must load the owl2 compat files right after it."""
    if "web/static/lib/owl/owl.js" not in text:
        return []
    if "owl3_compatibility_layer.js" in text or "owl2/utils.js" in text:
        return []
    line = text[: text.find("web/static/lib/owl/owl.js")].count("\n") + 1
    return [(line, "bundle ships owl.js without web/static/src/owl2/owl3_compatibility_layer.js")]


_REMOVED_HELPERS = re.compile(r"\b(makeMockEnv|makeDialogMockEnv)\s*\(|(?<![.\w])(asyncStep|waitForSteps)\s*\(")


def _removed_test_helpers(text: str, rel: str) -> list[tuple[int, str]]:
    """Flag removed web_test_helpers, unless the file defines a local helper with that name."""
    hits = []
    for m in _REMOVED_HELPERS.finditer(text):
        name = m.group(1) or m.group(2)
        if re.search(r"\b(?:function\s+|(?:const|let|var)\s+)" + name + r"\b", text):
            continue
        hits.append((text.count("\n", 0, m.start()) + 1, name))
    return hits


def _tour_extra_keys(text: str, rel: str) -> list[tuple[int, str]]:
    if "web_tour.tours" not in text:
        return []
    return [(text.count("\n", 0, m.start()) + 1, m.group(0)) for m in re.finditer(r"\bwait_for\s*:", text)]


